@app.patch("/admins/{admin_id}")
def update_admin_status(
    admin_id: int,
    request: AdminStatusUpdate
):

    connection = get_db_connection()
    cursor = connection.cursor(dictionary=True)

    try:
        cursor.execute("""
            SELECT
                id,
                user_id
            FROM user_admin
            WHERE id = %s
            LIMIT 1
        """, (admin_id,))

        admin = cursor.fetchone()

        if not admin:
            return {
                "success": False,
                "message": "Admin not found"
            }

        # SuperAdmin can never be modified.
        if admin["user_id"] == "testadmin":
            return {
                "success": False,
                "message": "SuperAdmin cannot be modified"
            }

        new_status = 1 if int(request.isActive) == 1 else 0

        cursor.execute("""
            UPDATE user_admin
            SET is_active = %s
            WHERE id = %s
        """, (
            new_status,
            admin_id
        ))

        connection.commit()

        return {
            "success": True,
            "message": "Admin status updated successfully",
            "isActive": new_status
        }

    except Exception as e:
        connection.rollback()

        return {
            "success": False,
            "message": str(e)
        }

    finally:
        cursor.close()
        connection.close()


@app.get("/profile")
def get_profile(user_id: str, role: str):
    connection = get_db_connection()
    cursor = connection.cursor(dictionary=True)

    try:
        if role == "admin":
            cursor.execute("""
                SELECT
                    ua.full_name AS fullName,
                    ua.user_id AS userId,
                    ua.mobile,
                    ua.is_active AS isActive
                FROM user_admin ua
                WHERE ua.user_id = %s
                LIMIT 1
            """, (user_id,))

            user = cursor.fetchone()

            if not user:
                return {
                    "success": False,
                    "message": "Profile not found"
                }

            user["role"] = "Administrator"
            user["schoolName"] = ""
            return {
                "success": True,
                **user
            }

        if role == "employee":
            cursor.execute("""
                SELECT
                    ua.full_name AS fullName,
                    ua.user_id AS userId,
                    ua.mobile,
                    ua.is_active AS isActive,
                    sm.school_name AS schoolName,
                    sm.is_active AS schoolIsActive
                FROM user_accountant ua
                LEFT JOIN school_master sm
                    ON sm.id = ua.school_id
                WHERE ua.user_id = %s
                LIMIT 1
            """, (user_id,))

            user = cursor.fetchone()

            if not user:
                return {
                    "success": False,
                    "message": "Profile not found"
                }

            user["role"] = "Employee"
            return {
                "success": True,
                **user
            }

        return {
            "success": False,
            "message": "Invalid profile role"
        }

    finally:
        cursor.close()
        connection.close()


