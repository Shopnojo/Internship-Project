@app.post("/payments")
def make_payment(payment: PaymentRequest):

    connection = get_db_connection()
    cursor = connection.cursor(dictionary=True)

    cursor.execute("""
        SELECT
            id,
            student_id,
            amount,
            COALESCE(penalty, 0) AS penalty,
            COALESCE(waiver, 0) AS waiver,
            net_amount,
            transaction_no
        FROM payment_entries
        WHERE id = %s
          AND is_paid = 0
          AND payment_date IS NULL
    """, (payment.due_id,))

    due = cursor.fetchone()

    if not due:
        cursor.close()
        connection.close()

        return {
            "success": False,
            "message": "Due not found or already paid"
        }

    today = date.today()

    # Keep the transaction number supplied by the Android app. If none was
    # supplied, generate one in the same format used by the existing website.
    transaction_no = payment.transaction_no or ("TXN" + str(secrets.randbelow(9_000_000_000) + 1_000_000_000))
    receipt_no = "BR/{} /{}".format(secrets.randbelow(900) + 100, today.year).replace(" ", "")
    bill_no = f"{payment.due_id:04d}/{today.year}"
    filename = f"receipt_{datetime.now().strftime('%Y%m%d%H%M%S%f')}.pdf"
    receipt_path = RECEIPT_DIR / filename

    # Fetch the same information used by the website receipt template.
    cursor.execute("""
        SELECT
            pe.amount,
            pe.net_amount,
            pe.payment_date,
            pe.payment_mode,
            pe.transaction_no,
            pe.student_id,
            pe.due_date,
            pem.payment_type,
            CONCAT(sm.first_name, ' ', sm.last_name) AS student_name,
            sm.student_id AS student_code,
            scm.class AS class_name,
            sec.section AS section_name,
            sch.school_name,
            sch.address_line_1 AS school_address,
            sch.logo AS school_logo
        FROM payment_entries pe
        LEFT JOIN payment_entry_master pem ON pe.entry_id = pem.id
        LEFT JOIN student_master sm ON pe.student_id = sm.id
        LEFT JOIN class_master scm ON sm.class_id = scm.id
        LEFT JOIN section_master sec ON sm.section_id = sec.id
        LEFT JOIN school_master sch ON sm.school_id = sch.id
        WHERE pe.id = %s
        LIMIT 1
    """, (payment.due_id,))
    payment_details = cursor.fetchone() or {}

    cursor.execute("""
        UPDATE payment_entries
        SET
            payment_date = %s,
            payment_confirm_date = %s,
            payment_recieve_date = %s,
            payment_mode = %s,
            transaction_no = %s,
            remarks = %s,
            is_paid = 1,
            bill_no = %s,
            receipt_no = %s,
            receipt_date = %s,
            receipt = %s,
            updated_ts = CURRENT_TIMESTAMP
        WHERE id = %s
    """, (
        today,
        today,
        today,
        payment.payment_mode,
        transaction_no,
        payment.remarks,
        bill_no,
        receipt_no,
        today,
        f"{BACKEND_BASE_URL}/receipts/{filename}",
        payment.due_id
    ))

    connection.commit()

    # The existing ClassAI payment transaction above remains authoritative.
    # After it succeeds, trigger the unchanged parent website's own receipt
    # generation for this same payment record. This is best-effort only, so
    # receipt generation can never make Collect Payment fail.
    try:
        form_data = urlencode({
            "payment_id": str(payment.due_id),
            "payment_date": today.isoformat(),
            "payment_mode": (payment.payment_mode or "").strip().upper(),
            "remarks": payment.remarks or "",
        }).encode("utf-8")

        receipt_request = Request(
            "https://classai.fixmyneed.in/submit-payment",
            data=form_data,
            method="POST",
            headers={
                "Content-Type": "application/x-www-form-urlencoded",
                "User-Agent": "ClassAI-Backend/1.0",
                "Origin": "https://classai.fixmyneed.in",
                "Referer": "https://classai.fixmyneed.in/offline-payment",
            },
        )

        class _NoRedirect(HTTPRedirectHandler):
            def redirect_request(self, req, fp, code, msg, headers, newurl):
                return None

        try:
            with build_opener(_NoRedirect).open(receipt_request, timeout=20) as response:
                website_status = response.status
        except HTTPError as exc:
            website_status = exc.code

        if not (200 <= website_status < 400):
            print(f"Website receipt generation returned HTTP {website_status} for payment {payment.due_id}")
    except (URLError, TimeoutError, OSError) as exc:
        print(f"Website receipt generation failed for payment {payment.due_id}: {exc}")

    # Generate the A4 receipt on the backend. The Bluetooth formatter is
    # completely separate and is intentionally not touched.
    _build_receipt_pdf(
        receipt_path=receipt_path,
        school_name=payment_details.get("school_name") or "",
        school_address=payment_details.get("school_address") or "",
        student_name=payment_details.get("student_name") or "",
        student_code=payment_details.get("student_code") or "",
        payment_type=payment_details.get("payment_type") or "",
        transaction_no=transaction_no,
        transaction_date=today.strftime("%d-%m-%Y"),
        payment_mode=payment.payment_mode,
        receipt_no=receipt_no,
        amount=float(due["net_amount"]),
        class_name=payment_details.get("class_name") or "",
        section_name=payment_details.get("section_name") or "",
        month=(payment_details.get("due_date") or today).strftime("%B-%Y") if hasattr((payment_details.get("due_date") or today), "strftime") else ""
    )

    cursor.close()
    connection.close()

    return {
        "success": True,
        "message": "Payment recorded successfully",
        "due_id": payment.due_id,
        "student_id": due["student_id"],
        "transaction_no": transaction_no,
        "amount": due["amount"],
        "penalty": due["penalty"],
        "waiver": due["waiver"],
        "net_amount": due["net_amount"],
        "payment_date": str(today),
        "payment_mode": payment.payment_mode,
        "receipt_no": receipt_no,
        "receipt": f"{BACKEND_BASE_URL}/receipts/{filename}"
    }


@app.get("/receipts/{filename}")
def get_receipt(filename: str):
    # Only serve generated PDF files from the dedicated receipt directory.
    safe_name = os.path.basename(filename)
    if safe_name != filename or not safe_name.lower().endswith(".pdf"):
        raise HTTPException(status_code=404, detail="Receipt not found")

    path = RECEIPT_DIR / safe_name
    if not path.is_file():
        raise HTTPException(status_code=404, detail="Receipt not found")

    return FileResponse(path, media_type="application/pdf", filename=safe_name)


def _build_receipt_pdf(
    receipt_path: Path,
    school_name: str,
    school_address: str,
    student_name: str,
    student_code: str,
    payment_type: str,
    transaction_no: str,
    transaction_date: str,
    payment_mode: str,
    receipt_no: str,
    amount: float,
    class_name: str,
    section_name: str,
    month: str,
):
    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "ReceiptTitle", parent=styles["Title"], fontName="Helvetica-Bold",
        fontSize=17, leading=20, alignment=TA_CENTER, spaceAfter=4
    )
    center = ParagraphStyle(
        "ReceiptCenter", parent=styles["Normal"], fontSize=10,
        leading=13, alignment=TA_CENTER
    )
    body = ParagraphStyle(
        "ReceiptBody", parent=styles["Normal"], fontSize=10,
        leading=14, alignment=TA_LEFT
    )

    doc = SimpleDocTemplate(
        str(receipt_path), pagesize=A4,
        rightMargin=22 * mm, leftMargin=22 * mm,
        topMargin=18 * mm, bottomMargin=18 * mm
    )

    amount_text = f"Rs. {amount:,.2f} /-"
    story = [
        Paragraph(school_name, title),
        Paragraph(school_address, center) if school_address else Spacer(1, 6),
        Spacer(1, 12),
        Paragraph("RECEIPT", title),
        Spacer(1, 8),
    ]

    details = [
        [Paragraph(f"<b>RECEIPT NO.</b> {receipt_no}", body), Paragraph(f"<b>TRANSACTION NO.</b> {transaction_no}", body)],
        [Paragraph(f"<b>TRANSACTION MODE.</b> {payment_mode}", body), Paragraph(f"<b>TRANSACTION DATE.</b> {transaction_date}", body)],
    ]
    table = Table(details, colWidths=[82 * mm, 82 * mm])
    table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(table)
    story.append(Spacer(1, 12))

    class_section = f" ({class_name}{(' - ' + section_name) if section_name else ''})" if class_name else ""
    story.append(Paragraph(
        f"Received with thanks for <b>{student_name}</b> - {student_code} for {payment_type or 'Fees'} for {month}{class_section}.",
        body
    ))
    story.append(Spacer(1, 12))
    story.append(Paragraph(f"Rupees {amount:,.2f} Only.", center))
    story.append(Spacer(1, 8))
    story.append(Paragraph(f"<b>{amount_text}</b>", center))
    story.append(Spacer(1, 42))
    story.append(Paragraph("This is a computer generated receipt. No signature required.", center))
    story.append(Spacer(1, 18))
    story.append(Paragraph("Powered by Eduplex Solutions Pvt. Ltd.", center))

    doc.build(story)


